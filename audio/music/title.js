/**
 * Band Wars — looping title theme
 * id: title
 *
 * Heroic 16-bit fanfare that quotes the football-field fight-song hook.
 * Key: Bb major. Tempo: 156 BPM. 4/4.
 *
 * Structure (16-step bars):
 *   Fanfare     bars  1–4
 *   Hook        bars  5–12  (fight-song hook)
 *   Turnaround  bars 13–16  (climbs back into the fanfare)
 * `loop: true`. 16 bars = 256 sixteenths ≈ 24.62s.
 *
 * Also exports `legacy` (4-channel 8-bit reduction). See instruments.js.
 */


function bars(label, ...measures) {
  const notes = [];
  measures.forEach((m, i) => {
    const sum = m.reduce((acc, ev) => acc + ev[1], 0);
    if (sum !== 16) throw new Error(label + ' bar ' + (i + 1) + ' is ' + sum + ' sixteenths, expected 16');
    notes.push(...m);
  });
  return notes;
}

